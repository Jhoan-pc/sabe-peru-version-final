/**
 * Tier 1: Feature Coverage & Pipeline Hygiene Test Suite
 * Formal SSOT: PROJECT.md Milestone E2E, specs/performance-spec.md, ORIGINAL_REQUEST.md R1
 * 
 * Verifies build pipeline integrity, static assets hygiene, zero dead Supabase
 * references in active production source code, and HTML image validity.
 */

import test, { describe } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const ROOT_DIR = process.cwd();

describe('Tier 1: Feature Coverage & Pipeline Hygiene', () => {

  describe('Feature 1.1: TypeScript Compilation (tsc --noEmit)', () => {
    test('T1.1.1: tsc --noEmit completes successfully with exit code 0', () => {
      assert.doesNotThrow(() => {
        execSync('npx tsc --noEmit', {
          cwd: ROOT_DIR,
          stdio: 'pipe',
          timeout: 25000
        });
      }, 'Typecheck failed: tsc --noEmit should exit with code 0');
    });

    test('T1.1.2: tsconfig.json exists, is valid JSONC, and specifies strict typechecking options', () => {
      const tsconfigPath = path.join(ROOT_DIR, 'tsconfig.json');
      assert.ok(fs.existsSync(tsconfigPath), 'tsconfig.json must exist');
      const rawContent = fs.readFileSync(tsconfigPath, 'utf8');
      // Strip comments to parse JSONC
      const stripped = rawContent.replace(/\/\*[\s\S]*?\*\/|\/\/.*/g, '');
      const tsconfig = JSON.parse(stripped);
      assert.ok(tsconfig.compilerOptions, 'tsconfig must have compilerOptions');
      assert.equal(tsconfig.compilerOptions.noEmit, true, 'noEmit should be true in tsconfig');
      assert.equal(tsconfig.compilerOptions.strict, true, 'strict mode should be true');
    });

    test('T1.1.3: Core TypeScript source files in src/ exist and have valid syntax', () => {
      const coreFiles = ['main.ts', 'admin.ts', 'reservations.ts', 'firebase.ts'];
      for (const file of coreFiles) {
        const fullPath = path.join(ROOT_DIR, 'src', file);
        assert.ok(fs.existsSync(fullPath), `Expected ${file} to exist in src/`);
        const content = fs.readFileSync(fullPath, 'utf8');
        assert.ok(content.length > 50, `${file} should not be empty`);
      }
    });

    test('T1.1.4: Node.js strip-types engine can parse reservations.ts without syntax errors', () => {
      const resPath = path.join(ROOT_DIR, 'src', 'reservations.ts');
      assert.ok(fs.existsSync(resPath), 'src/reservations.ts must exist');
      const content = fs.readFileSync(resPath, 'utf8');
      assert.match(content, /export\s+interface\s+ReservationSlot/, 'reservations.ts must export ReservationSlot interface');
      assert.match(content, /export\s+async\s+function\s+getAvailableSlots/, 'reservations.ts must export getAvailableSlots');
    });

    test('T1.1.5: tsc --noEmit execution finishes in under 20 seconds (performance budget)', () => {
      const start = Date.now();
      execSync('npx tsc --noEmit', { cwd: ROOT_DIR, stdio: 'pipe', timeout: 20000 });
      const duration = Date.now() - start;
      assert.ok(duration < 20000, `Typecheck took ${duration}ms, exceeding budget`);
    });
  });

  describe('Feature 1.2: Vite Production Bundling (vite build)', () => {
    test('T1.2.1: vite build executes and produces exit code 0', () => {
      assert.doesNotThrow(() => {
        execSync('npx vite build', {
          cwd: ROOT_DIR,
          stdio: 'pipe',
          timeout: 30000
        });
      }, 'Production build failed: vite build should exit with code 0');
    });

    test('T1.2.2: Build emits all 4 multi-page HTML entrypoints in dist/', () => {
      const expectedHtml = ['index.html', 'carta.html', 'admin.html', 'experiencia.html'];
      for (const html of expectedHtml) {
        const distFile = path.join(ROOT_DIR, 'dist', html);
        assert.ok(fs.existsSync(distFile), `dist/${html} must be generated by build`);
        const content = fs.readFileSync(distFile, 'utf8');
        assert.match(content, /<!doctype\s+html>/i, `dist/${html} must have valid HTML doctype`);
      }
    });

    test('T1.2.3: Production assets directory contains generated CSS and JS chunks', () => {
      const assetsDir = path.join(ROOT_DIR, 'dist', 'assets');
      assert.ok(fs.existsSync(assetsDir), 'dist/assets directory must exist');
      const files = fs.readdirSync(assetsDir);
      const jsFiles = files.filter(f => f.endsWith('.js'));
      const cssFiles = files.filter(f => f.endsWith('.css'));
      assert.ok(jsFiles.length >= 3, `Expected at least 3 JS chunks, found ${jsFiles.length}`);
      assert.ok(cssFiles.length >= 1, `Expected at least 1 CSS bundle, found ${cssFiles.length}`);
    });

    test('T1.2.4: Generated HTML files reference valid asset bundles without 404 links', () => {
      const distIndex = path.join(ROOT_DIR, 'dist', 'index.html');
      const content = fs.readFileSync(distIndex, 'utf8');
      const scriptMatches = [...content.matchAll(/<script[^>]+src=["']\/assets\/([^"']+)["']/g)].map(m => m[1]);
      assert.ok(scriptMatches.length > 0, 'dist/index.html must reference bundled scripts');
      for (const scriptFile of scriptMatches) {
        const fullScriptPath = path.join(ROOT_DIR, 'dist', 'assets', scriptFile);
        assert.ok(fs.existsSync(fullScriptPath), `Asset file ${scriptFile} referenced in index.html must exist on disk`);
      }
    });

    test('T1.2.5: Build output files are non-empty and satisfy size limits', () => {
      const distIndex = path.join(ROOT_DIR, 'dist', 'index.html');
      const stat = fs.statSync(distIndex);
      assert.ok(stat.size > 1000, 'dist/index.html should be larger than 1KB');
      assert.ok(stat.size < 500000, 'dist/index.html should be under 500KB');
    });
  });

  describe('Feature 1.3: Zero Active Supabase References in src/', () => {
    test('T1.3.1: src/main.ts contains zero active imports of @supabase/supabase-js or ./supabase', () => {
      const mainTs = fs.readFileSync(path.join(ROOT_DIR, 'src', 'main.ts'), 'utf8');
      const activeImports = [...mainTs.matchAll(/^import\s+.*from\s+['"](@supabase\/supabase-js|\.\/supabase)['"]/gm)];
      assert.equal(activeImports.length, 0, 'src/main.ts must have zero active imports of Supabase');
    });

    test('T1.3.2: src/admin.ts contains zero active imports of @supabase/supabase-js or ./supabase', () => {
      const adminTs = fs.readFileSync(path.join(ROOT_DIR, 'src', 'admin.ts'), 'utf8');
      const activeImports = [...adminTs.matchAll(/^import\s+.*from\s+['"](@supabase\/supabase-js|\.\/supabase)['"]/gm)];
      assert.equal(activeImports.length, 0, 'src/admin.ts must have zero active imports of Supabase');
    });

    test('T1.3.3: src/reservations.ts contains zero references to Supabase', () => {
      const reservationsTs = fs.readFileSync(path.join(ROOT_DIR, 'src', 'reservations.ts'), 'utf8');
      assert.doesNotMatch(reservationsTs, /supabase/i, 'src/reservations.ts must have zero references to Supabase');
    });

    test('T1.3.4: Production bundle in dist/assets does not instantiate active Supabase client', () => {
      const assetsDir = path.join(ROOT_DIR, 'dist', 'assets');
      const files = fs.readdirSync(assetsDir).filter(f => f.endsWith('.js'));
      for (const f of files) {
        const code = fs.readFileSync(path.join(assetsDir, f), 'utf8');
        assert.doesNotMatch(code, /createClient\(['"]https:\/\/[a-z0-9]+\.supabase\.co/i,
          `Bundle chunk ${f} must not create active Supabase client instances`);
      }
    });

    test('T1.3.5: No production module imports src/supabase.ts', () => {
      const srcFiles = ['src/main.ts', 'src/admin.ts', 'src/reservations.ts', 'src/firebase.ts'];
      for (const f of srcFiles) {
        const code = fs.readFileSync(path.join(ROOT_DIR, f), 'utf8');
        assert.doesNotMatch(code, /from\s+['"]\.\/supabase['"]/, `${f} must not import ./supabase`);
      }
    });
  });

  describe('Feature 1.4: HTML Image Integrity (No Duplicate or Broken Image Tags)', () => {
    test('T1.4.1: index.html has zero duplicate src attributes across all img tags', () => {
      const content = fs.readFileSync(path.join(ROOT_DIR, 'index.html'), 'utf8');
      const matches = [...content.matchAll(/<img[^>]+src=["']([^"']+)["']/gi)].map(m => m[1]);
      assert.ok(matches.length > 0, 'index.html should have img tags');
      const duplicates = matches.filter((item, index) => matches.indexOf(item) !== index);
      assert.deepEqual(duplicates, [], `Found duplicate img src in index.html: ${duplicates.join(', ')}`);
    });

    test('T1.4.2: Content images in index.html, carta.html and experiencia.html do not have literal undefined/null in src', () => {
      const files = ['index.html', 'carta.html', 'experiencia.html'];
      for (const file of files) {
        const content = fs.readFileSync(path.join(ROOT_DIR, file), 'utf8');
        const brokenSrcs = [...content.matchAll(/<img[^>]+src=["'](undefined|null|\[object\s+Object\])["']/gi)];
        assert.equal(brokenSrcs.length, 0, `${file} must not contain broken undefined/null in img src`);
      }
    });

    test('T1.4.3: admin.html preview placeholders all have explicit preview IDs and handle dynamic hydration', () => {
      const content = fs.readFileSync(path.join(ROOT_DIR, 'admin.html'), 'utf8');
      const imgTags = [...content.matchAll(/<img\b([^>]*)>/gi)].map(m => m[1]);
      for (const attrs of imgTags) {
        // Every img in admin.html is a dynamic preview and must have an id starting with preview-
        assert.match(attrs, /\bid=["']preview-[^"']+["']/i,
          `Every img tag in admin.html must be a designated preview element with id="preview-...". Found: <img ${attrs}>`);
      }
    });

    test('T1.4.4: Local asset images referenced in HTML exist in public/assets/', () => {
      const htmlFiles = ['index.html', 'carta.html', 'experiencia.html'];
      for (const file of htmlFiles) {
        const content = fs.readFileSync(path.join(ROOT_DIR, file), 'utf8');
        const localMatches = [...content.matchAll(/src=["']\/assets\/([^"']+)["']/gi)].map(m => m[1]);
        for (const assetName of localMatches) {
          const publicAssetPath = path.join(ROOT_DIR, 'public', 'assets', assetName);
          assert.ok(fs.existsSync(publicAssetPath), `Referenced asset /assets/${assetName} in ${file} must exist in public/assets/`);
        }
      }
    });

    test('T1.4.5: All static img tags in index.html and experiencia.html include alt attributes', () => {
      const htmlFiles = ['index.html', 'experiencia.html'];
      for (const file of htmlFiles) {
        const content = fs.readFileSync(path.join(ROOT_DIR, file), 'utf8');
        const imgTags = [...content.matchAll(/<img\b([^>]*)>/gi)].map(m => m[1]);
        for (const attrs of imgTags) {
          assert.match(attrs, /\balt=["'][^"']*["']/i, `All img tags in ${file} must provide an alt attribute. Found: <img ${attrs}>`);
        }
      }
    });
  });
});
